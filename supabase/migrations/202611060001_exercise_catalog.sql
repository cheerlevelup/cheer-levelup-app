-- Katalog ćwiczeń: nazwa + link do filmiku. Ćwiczenie dodane do treningu/planu
-- o tej samej nazwie (bez względu na wielkość liter i spacje na brzegach)
-- automatycznie dostaje link z katalogu.

create table if not exists public.exercise_catalog (
  id bigint generated by default as identity primary key,
  name text not null,
  link_url text,
  created_at timestamptz not null default now()
);

create unique index if not exists exercise_catalog_name_lower_idx
  on public.exercise_catalog (lower(btrim(name)));

alter table public.exercise_catalog enable row level security;

drop policy if exists "Coach can manage exercise catalog" on public.exercise_catalog;
create policy "Coach can manage exercise catalog"
  on public.exercise_catalog for all
  to authenticated
  using ((select auth.email()) = 'cheerlevelup@gmail.com')
  with check ((select auth.email()) = 'cheerlevelup@gmail.com');

notify pgrst, 'reload schema';
