-- Periodyzacja (profil drużyny → zakładka „Periodyzacja").
-- Hierarchia: Program treningowy → Makrocykl → Mezocykl → Mikrocykl → Jednostka treningowa.
--
-- Nie dublujemy istniejącego systemu planów:
--   * każdy program ma swój plan treningowy (workout_plans) — przypisania, indywidualne
--     parametry zawodniczek, uzupełnianie wyników i statystyki działają jak dotąd,
--   * mikrocykl = tydzień planu (workout_weeks) + nowe kolumny mesocycle_id / end_date / goal,
--   * jednostka treningowa = trening planu (workout_days) + nowa kolumna goal,
--   * wydarzenia (zawody, obozy, przerwy) = kalendarz sezonu (calendar_events).
-- Uruchom w Supabase SQL Editor.

create table if not exists public.periodization_programs (
  id bigint generated by default as identity primary key,
  -- null = szablon dostępny dla wszystkich drużyn
  group_id bigint references public.groups(id) on delete cascade,
  plan_id bigint references public.workout_plans(id) on delete set null,
  name text not null,
  description text,
  goal text,
  start_date date,
  end_date date,
  archived boolean not null default false,
  is_template boolean not null default false,
  created_at timestamptz not null default now()
);
create index if not exists periodization_programs_group_idx on public.periodization_programs (group_id);

create table if not exists public.periodization_macrocycles (
  id bigint generated by default as identity primary key,
  program_id bigint not null references public.periodization_programs(id) on delete cascade,
  name text not null,
  goal text,
  start_date date,
  end_date date,
  notes text,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists periodization_macrocycles_program_idx on public.periodization_macrocycles (program_id);

create table if not exists public.periodization_mesocycles (
  id bigint generated by default as identity primary key,
  program_id bigint not null references public.periodization_programs(id) on delete cascade,
  -- null = mezocykl bez makrocyklu (struktura nie musi być pełna)
  macrocycle_id bigint references public.periodization_macrocycles(id) on delete set null,
  name text not null,
  -- np. siła maksymalna, hipertrofia, moc, przygotowanie ogólne
  goal text,
  weeks_count int not null default 4,
  start_date date,
  end_date date,
  notes text,
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists periodization_mesocycles_program_idx on public.periodization_mesocycles (program_id);

-- Mikrocykl = tydzień planu
alter table public.workout_weeks
  add column if not exists mesocycle_id bigint references public.periodization_mesocycles(id) on delete set null,
  add column if not exists end_date date,
  add column if not exists goal text;

-- Jednostka treningowa = trening planu
alter table public.workout_days add column if not exists goal text;

-- Szablony (programów i jednostek) trzymane jako ukryte plany:
-- 'program' = plan szablonu programu, 'unit' = biblioteka szablonów jednostek
alter table public.workout_plans add column if not exists template_kind text;

alter table public.periodization_programs enable row level security;
alter table public.periodization_macrocycles enable row level security;
alter table public.periodization_mesocycles enable row level security;

