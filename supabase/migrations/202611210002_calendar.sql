-- Kalendarz sezonu (wrzesień–sierpień): wydarzenia (zawody, pokazy, ferie,
-- obozy, inne) przypisane do grup oraz cykliczne treningi drużyn.
-- Do tego widżety "odliczanie do..." (liczba dni + liczba treningów do wydarzenia).

create table if not exists public.calendar_events (
  id bigint generated by default as identity primary key,
  title text not null,
  -- competition | show | camp | break | training | other
  event_type text not null default 'other',
  start_date date not null,
  end_date date,
  start_time time,
  end_time time,
  location text,
  notes text,
  -- grupy, których dotyczy wydarzenie; all_groups = wszystkie (także nowe)
  group_ids bigint[] not null default '{}',
  all_groups boolean not null default false,
  -- powtarzanie (treningi): dni tygodnia 1=pon ... 7=niedz, do kiedy
  recurrence_weekdays smallint[],
  recurrence_until date,
  -- pojedyncze odwołane terminy powtarzanego wydarzenia
  excluded_dates date[] not null default '{}',
  -- przerwa (ferie, święta): w tym czasie nie ma treningów wskazanych grup
  cancels_trainings boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists calendar_events_start_date_idx on public.calendar_events (start_date);

create table if not exists public.calendar_countdowns (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.calendar_events(id) on delete cascade,
  -- drużyny, dla których liczymy treningi; puste = grupy wydarzenia
  group_ids bigint[] not null default '{}',
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

alter table public.calendar_events enable row level security;
alter table public.calendar_countdowns enable row level security;

